-- The job queue's role and SECURITY DEFINER functions (ADR 0005 section 3, ADR 0002 section 3).
--
-- Run as the superuser, after `alembic upgrade head`, in ONE transaction:
--
--   psql --single-transaction -v ON_ERROR_STOP=1 -h HOST -U postgres -d ownvitals -f 20-queue.sql
--
-- compose runs it in the one-shot `db-functions` service; the database tests run the same file
-- as the test superuser. It is plain SQL (no psql meta-commands), so any client can run it.
--
-- Idempotent: running it again creates or repairs the role (attributes, memberships, settings),
-- revokes every privilege ownvitals_queue holds anywhere (not its own EXECUTE on the functions it
-- owns), re-grants exactly the list below, and replaces the functions with their ACLs and
-- version comment. Migrations never create these functions, and no other user-defined function,
-- operator, trigger or rule may exist (the check below). The functions' search_path is
-- pg_catalog, pg_temp (public left out, every table schema-qualified; Postgres never looks up
-- functions or operators in pg_temp), so no object in public can shadow a built-in they call.
-- A migration that changes a column the functions read bumps the version (QUEUE_VERSION in
-- ownvitals.db.queue_check) and the comments below in the same PR; the expected md5 of each
-- function lives in ownvitals/db/queue_digests.py (regenerated by CI, see docs/dev/jobs.md).

DO $$
BEGIN
  IF NOT coalesce((SELECT rolsuper FROM pg_catalog.pg_roles WHERE rolname = current_user), false)
  THEN
    RAISE EXCEPTION 'this script must run as the superuser';
  END IF;
  IF NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = 'ownvitals_app') THEN
    RAISE EXCEPTION 'ownvitals_app does not exist; run docker/postgres/init/10-roles.sql first';
  END IF;
  IF pg_catalog.to_regclass('public.jobs') IS NULL
     OR pg_catalog.to_regclass('public.job_events') IS NULL THEN
    RAISE EXCEPTION 'public.jobs or public.job_events does not exist; run the migrations first';
  END IF;
  IF NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = 'ownvitals_queue') THEN
    CREATE ROLE ownvitals_queue NOLOGIN;
  END IF;
END $$;

-- The role: no login, no other power than BYPASSRLS for its own functions; member of no role and
-- nobody a member of it; no role settings.
ALTER ROLE ownvitals_queue WITH NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION
  BYPASSRLS NOINHERIT CONNECTION LIMIT -1 PASSWORD NULL;
ALTER ROLE ownvitals_queue RESET ALL;

DO $$
DECLARE
  r record;
BEGIN
  FOR r IN SELECT datname FROM pg_catalog.pg_database d JOIN pg_catalog.pg_db_role_setting s
                ON s.setdatabase = d.oid
             WHERE s.setrole = 'ownvitals_queue'::regrole LOOP
    EXECUTE format('ALTER ROLE ownvitals_queue IN DATABASE %I RESET ALL', r.datname);
  END LOOP;
  FOR r IN SELECT g.rolname AS granted, m.rolname AS member, gr.rolname AS grantor
             FROM pg_catalog.pg_auth_members am
             JOIN pg_catalog.pg_roles g ON g.oid = am.roleid
             JOIN pg_catalog.pg_roles m ON m.oid = am.member
             JOIN pg_catalog.pg_roles gr ON gr.oid = am.grantor
            WHERE 'ownvitals_queue' IN (g.rolname, m.rolname) LOOP
    EXECUTE format('REVOKE %I FROM %I GRANTED BY %I CASCADE', r.granted, r.member, r.grantor);
  END LOOP;
END $$;

-- ownvitals_queue owns the three functions and nothing else, and has no default privileges of
-- its own. Anything else is not repaired automatically (dropping or reassigning it could lose
-- data): the script stops and names it.
DO $$
DECLARE
  q oid := 'ownvitals_queue'::regrole;
  r record;
BEGIN
  FOR r IN SELECT s.classid::regclass::text AS catalog, s.objid, s.dbid,
                  pg_catalog.pg_describe_object(s.classid, s.objid, 0) AS what
             FROM pg_catalog.pg_shdepend s
            WHERE s.refclassid = 'pg_catalog.pg_authid'::regclass AND s.refobjid = q
              AND s.deptype = 'o' LOOP
    IF r.dbid <> (SELECT oid FROM pg_catalog.pg_database WHERE datname = current_database())
       OR r.catalog <> 'pg_proc'
       OR NOT EXISTS (SELECT FROM pg_catalog.pg_proc p
                        JOIN pg_catalog.pg_namespace n ON n.oid = p.pronamespace
                       WHERE p.oid = r.objid AND n.nspname = 'public'
                         AND p.proname IN ('queue_claim', 'queue_reap', 'queue_stats')) THEN
      RAISE EXCEPTION 'ownvitals_queue owns % (catalog %, object %); it may own only the queue '
        'functions: drop or reassign it by hand', coalesce(r.what, '?'), r.catalog, r.objid;
    END IF;
  END LOOP;
  IF EXISTS (SELECT FROM pg_catalog.pg_default_acl WHERE defaclrole = q) THEN
    RAISE EXCEPTION 'default privileges exist FOR ROLE ownvitals_queue; remove them by hand';
  END IF;
END $$;

-- Revoke every privilege ownvitals_queue holds, found through pg_shdepend (every ACL entry naming
-- a role is recorded there, for every object kind). A kind this block does not know stops the
-- script: repair it by hand rather than run with an unknown privilege.
DO $$
DECLARE
  q oid := 'ownvitals_queue'::regrole;
  d record;
  g record;
  target text;
BEGIN
  FOR d IN SELECT s.classid::regclass::text AS catalog, s.objid, s.objsubid, s.dbid
             FROM pg_catalog.pg_shdepend s
            WHERE s.refclassid = 'pg_catalog.pg_authid'::regclass AND s.refobjid = q
              AND s.deptype = 'a'
              AND s.dbid IN (0, (SELECT oid FROM pg_catalog.pg_database
                                  WHERE datname = current_database())) LOOP
    IF d.catalog = 'pg_class' AND d.objsubid = 0 THEN
      SELECT CASE WHEN c.relkind = 'S' THEN 'SEQUENCE ' ELSE 'TABLE ' END || c.oid::regclass::text
        INTO target FROM pg_catalog.pg_class c WHERE c.oid = d.objid;
      FOR g IN SELECT DISTINCT a.grantor::regrole::text AS grantor
                 FROM pg_catalog.pg_class c, aclexplode(c.relacl) a
                WHERE c.oid = d.objid AND a.grantee = q LOOP
        EXECUTE format('SET LOCAL ROLE %s', g.grantor);
        EXECUTE format('REVOKE ALL ON %s FROM ownvitals_queue CASCADE', target);
        EXECUTE 'RESET ROLE';
      END LOOP;
    ELSIF d.catalog = 'pg_class' THEN
      FOR g IN SELECT DISTINCT a.grantor::regrole::text AS grantor, t.attname
                 FROM pg_catalog.pg_attribute t, aclexplode(t.attacl) a
                WHERE t.attrelid = d.objid AND t.attnum = d.objsubid AND a.grantee = q LOOP
        EXECUTE format('SET LOCAL ROLE %s', g.grantor);
        EXECUTE format('REVOKE ALL (%I) ON TABLE %s FROM ownvitals_queue CASCADE',
                       g.attname, d.objid::regclass::text);
        EXECUTE 'RESET ROLE';
      END LOOP;
    ELSIF d.catalog = 'pg_namespace' THEN
      FOR g IN SELECT DISTINCT a.grantor::regrole::text AS grantor, n.nspname
                 FROM pg_catalog.pg_namespace n, aclexplode(n.nspacl) a
                WHERE n.oid = d.objid AND a.grantee = q LOOP
        EXECUTE format('SET LOCAL ROLE %s', g.grantor);
        EXECUTE format('REVOKE ALL ON SCHEMA %I FROM ownvitals_queue CASCADE', g.nspname);
        EXECUTE 'RESET ROLE';
      END LOOP;
    ELSIF d.catalog = 'pg_proc' THEN
      FOR g IN SELECT DISTINCT a.grantor::regrole::text AS grantor
                 FROM pg_catalog.pg_proc p, aclexplode(p.proacl) a
                WHERE p.oid = d.objid AND a.grantee = q AND p.proowner <> q LOOP
        EXECUTE format('SET LOCAL ROLE %s', g.grantor);
        EXECUTE format('REVOKE ALL ON ROUTINE %s FROM ownvitals_queue CASCADE',
                       d.objid::regprocedure::text);
        EXECUTE 'RESET ROLE';
      END LOOP;
    ELSIF d.catalog = 'pg_database' THEN
      FOR g IN SELECT DISTINCT a.grantor::regrole::text AS grantor, b.datname
                 FROM pg_catalog.pg_database b, aclexplode(b.datacl) a
                WHERE b.oid = d.objid AND a.grantee = q LOOP
        EXECUTE format('SET LOCAL ROLE %s', g.grantor);
        EXECUTE format('REVOKE ALL ON DATABASE %I FROM ownvitals_queue CASCADE', g.datname);
        EXECUTE 'RESET ROLE';
      END LOOP;
    ELSIF d.catalog = 'pg_default_acl' THEN
      FOR g IN SELECT x.defaclrole::regrole::text AS owner, x.defaclnamespace,
                      CASE x.defaclobjtype WHEN 'r' THEN 'TABLES' WHEN 'S' THEN 'SEQUENCES'
                           WHEN 'f' THEN 'FUNCTIONS' WHEN 'T' THEN 'TYPES'
                           WHEN 'n' THEN 'SCHEMAS' END AS kind
                 FROM pg_catalog.pg_default_acl x WHERE x.oid = d.objid LOOP
        EXECUTE format('ALTER DEFAULT PRIVILEGES FOR ROLE %s %s REVOKE ALL ON %s '
                       'FROM ownvitals_queue CASCADE', g.owner,
                       CASE WHEN g.defaclnamespace = 0 THEN ''
                            ELSE 'IN SCHEMA ' || quote_ident(g.defaclnamespace::regnamespace::text)
                       END, g.kind);
      END LOOP;
    ELSE
      RAISE EXCEPTION 'ownvitals_queue holds a privilege on % %; revoke it by hand',
        d.catalog, d.objid;
    END IF;
  END LOOP;
END $$;

-- Exactly these (ADR 0005 section 3).
GRANT USAGE ON SCHEMA public TO ownvitals_queue;
GRANT SELECT, UPDATE ON TABLE public.jobs TO ownvitals_queue;
GRANT SELECT, INSERT ON TABLE public.job_events TO ownvitals_queue;

-- Any other function under one of the three names (an overload) goes: each must exist once.
DO $$
DECLARE
  r record;
BEGIN
  FOR r IN SELECT p.oid::regprocedure::text AS signature
             FROM pg_catalog.pg_proc p JOIN pg_catalog.pg_namespace n ON n.oid = p.pronamespace
            WHERE n.nspname = 'public'
              AND p.proname IN ('queue_claim', 'queue_reap', 'queue_stats')
              AND p.oid::regprocedure::text NOT IN (
                'queue_claim(text,integer,text[])', 'queue_reap(integer)', 'queue_stats()') LOOP
    EXECUTE format('DROP ROUTINE public.%s', r.signature);
  END LOOP;
END $$;

-- No user code may run as ownvitals_queue (ADR 0005 section 3): no other user function,
-- operator, trigger or rule, and no expression calling a built-in that runs SQL text or changes
-- settings. The queue check (ownvitals.db.queue_check) refuses the same: stop here, naming each
-- object as it and guard 9 do. The allowed database code that later issues add (the admin audit
-- guard of #12, ensure_month_partitions of #21, the webhook-secret function) is admitted here
-- exactly, pinned by digest, in the PR that adds it.
DO $$
DECLARE
  v_found text;
BEGIN
  SELECT string_agg(x.what, ', ' ORDER BY x.what) INTO v_found FROM (
    SELECT 'function ' || n.nspname || '.' || p.proname || '('
           || pg_catalog.oidvectortypes(p.proargtypes) || ')' AS what
      FROM pg_catalog.pg_proc p JOIN pg_catalog.pg_namespace n ON n.oid = p.pronamespace
     WHERE NOT (n.nspname = 'public' AND p.proname IN ('queue_claim', 'queue_reap', 'queue_stats'))
       AND (p.oid >= 16384 OR n.nspname = 'public'
            OR (n.nspname NOT IN ('pg_catalog', 'information_schema', 'pg_toast')
                AND n.nspname !~ '^pg_(toast_)?temp_[0-9]+$'))
    UNION ALL
    SELECT 'operator ' || n.nspname || '.' || o.oprname || '('
           || CASE WHEN o.oprleft = 0 THEN 'NONE' ELSE o.oprleft::regtype::text END || ', '
           || CASE WHEN o.oprright = 0 THEN 'NONE' ELSE o.oprright::regtype::text END || ')'
      FROM pg_catalog.pg_operator o JOIN pg_catalog.pg_namespace n ON n.oid = o.oprnamespace
     WHERE o.oid >= 16384 OR n.nspname = 'public'
        OR (n.nspname NOT IN ('pg_catalog', 'information_schema', 'pg_toast')
            AND n.nspname !~ '^pg_(toast_)?temp_[0-9]+$')
    UNION ALL
    SELECT 'trigger ' || t.tgname || ' on ' || n.nspname || '.' || c.relname
      FROM pg_catalog.pg_trigger t JOIN pg_catalog.pg_class c ON c.oid = t.tgrelid
      JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace WHERE NOT t.tgisinternal
    UNION ALL
    SELECT 'rule ' || w.rulename || ' on ' || n.nspname || '.' || c.relname
      FROM pg_catalog.pg_rewrite w JOIN pg_catalog.pg_class c ON c.oid = w.ev_class
      JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
     WHERE w.oid >= 16384 AND w.rulename <> '_RETURN'
    UNION SELECT 'built-in ' || f.proname || ' in ' || e.what FROM (
      SELECT 'the default of ' || n.nspname || '.' || c.relname || '.' || a.attname AS what,
             d.adbin::text AS tree
        FROM pg_catalog.pg_attrdef d JOIN pg_catalog.pg_class c ON c.oid = d.adrelid
        JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
        JOIN pg_catalog.pg_attribute a ON a.attrelid = d.adrelid AND a.attnum = d.adnum
      UNION ALL
      SELECT 'constraint ' || k.conname || ' on ' || n.nspname || '.'
             || coalesce(c.relname, y.typname), k.conbin::text
        FROM pg_catalog.pg_constraint k JOIN pg_catalog.pg_namespace n ON n.oid = k.connamespace
        LEFT JOIN pg_catalog.pg_class c ON c.oid = k.conrelid
        LEFT JOIN pg_catalog.pg_type y ON y.oid = k.contypid WHERE k.conbin IS NOT NULL
      UNION ALL
      SELECT 'index ' || n.nspname || '.' || c.relname, concat(i.indexprs::text, i.indpred::text)
        FROM pg_catalog.pg_index i JOIN pg_catalog.pg_class c ON c.oid = i.indexrelid
        JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
      UNION ALL
      SELECT 'the default of type ' || n.nspname || '.' || y.typname, y.typdefaultbin::text
        FROM pg_catalog.pg_type y JOIN pg_catalog.pg_namespace n ON n.oid = y.typnamespace
      UNION ALL
      SELECT 'the partition key of ' || n.nspname || '.' || c.relname, x.partexprs::text
        FROM pg_catalog.pg_partitioned_table x JOIN pg_catalog.pg_class c ON c.oid = x.partrelid
        JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
    ) e
    CROSS JOIN LATERAL pg_catalog.regexp_matches(e.tree, '[:]funcid ([0-9]+)', 'g') m
    JOIN pg_catalog.pg_proc f ON f.oid = m[1]::oid
    WHERE f.pronamespace = 'pg_catalog'::regnamespace AND f.proname IN ('query_to_xml',
      'query_to_xmlschema', 'query_to_xml_and_xmlschema', 'cursor_to_xml', 'cursor_to_xmlschema',
      'table_to_xml', 'table_to_xmlschema', 'table_to_xml_and_xmlschema', 'schema_to_xml',
      'schema_to_xmlschema', 'schema_to_xml_and_xmlschema', 'database_to_xml',
      'database_to_xmlschema', 'database_to_xml_and_xmlschema', 'ts_stat', 'ts_rewrite',
      'set_config')) x;
  IF v_found IS NOT NULL THEN
    RAISE EXCEPTION 'the database holds % besides the queue functions; drop them by hand '
      '(ADR 0005 section 3)', v_found;
  END IF;
END $$;

-- Claim the next queued job of one of p_kinds whose attempts are not spent. A row whose update
-- fails is skipped (and stays locked until this transaction ends), so it cannot stall the queue.
CREATE OR REPLACE FUNCTION public.queue_claim(p_worker text, p_lease_seconds integer,
                                              p_kinds text[])
  RETURNS TABLE (job_id uuid, owner_id uuid, lease_version bigint)
  LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, pg_temp
AS $$
#variable_conflict use_column
DECLARE
  v_skipped uuid[] := '{}';
  v_id uuid;
  v_owner uuid;
  v_version bigint;
  v_seq bigint;
  v_attempt integer;
BEGIN
  IF p_worker IS NULL OR p_worker !~ '^[A-Za-z0-9._:-]{1,100}$' THEN
    RAISE EXCEPTION 'invalid worker id' USING ERRCODE = '22023';
  END IF;
  IF p_lease_seconds IS NULL OR p_lease_seconds < 30 OR p_lease_seconds > 600 THEN
    RAISE EXCEPTION 'p_lease_seconds must be 30 to 600' USING ERRCODE = '22023';
  END IF;
  IF p_kinds IS NULL OR cardinality(p_kinds) = 0 THEN
    RETURN;
  END IF;
  FOR i IN 1..10 LOOP
    SELECT j.id, j.owner_id INTO v_id, v_owner
      FROM public.jobs j
     WHERE j.state = 'queued' AND j.available_at <= now() AND j.attempt < j.max_attempts
       AND j.kind = ANY (p_kinds) AND j.id <> ALL (v_skipped)
     ORDER BY j.available_at, j.created_at
     LIMIT 1
       FOR UPDATE SKIP LOCKED;
    IF NOT FOUND THEN
      RETURN;
    END IF;
    BEGIN
      UPDATE public.jobs j
         SET state = 'running', attempt = j.attempt + 1, lease_version = j.lease_version + 1,
             leased_by = p_worker, lease_expires_at = now() + make_interval(secs => p_lease_seconds),
             heartbeat_at = now(), started_at = coalesce(j.started_at, now()),
             next_seq = j.next_seq + 1, updated_at = now()
       WHERE j.id = v_id
      RETURNING j.lease_version, j.next_seq, j.attempt INTO v_version, v_seq, v_attempt;
      INSERT INTO public.job_events (owner_id, job_id, seq, kind, payload, lease_version)
      VALUES (v_owner, v_id, v_seq, 'claimed', jsonb_build_object('attempt', v_attempt),
              v_version);
      PERFORM pg_notify('job_events', v_id::text);
    EXCEPTION WHEN OTHERS THEN
      v_skipped := v_skipped || v_id;
      CONTINUE;
    END;
    job_id := v_id;
    owner_id := v_owner;
    lease_version := v_version;
    RETURN NEXT;
    RETURN;
  END LOOP;
END $$;

-- Running jobs whose lease expired: the token goes up (fencing the old holder), then cancelled
-- if a cancel was requested, queued with backoff while attempts remain, else failed/lease_lost.
-- Queued rows with spent attempts (should not exist) fail as internal. A bad row is skipped.
CREATE OR REPLACE FUNCTION public.queue_reap(p_limit integer)
  RETURNS integer
  LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, pg_temp
AS $$
DECLARE
  r record;
  v_done integer := 0;
  v_state text;
  v_at timestamptz;
  v_version bigint;
  v_seq bigint;
BEGIN
  IF p_limit IS NULL OR p_limit < 1 OR p_limit > 100 THEN
    RAISE EXCEPTION 'p_limit must be 1 to 100' USING ERRCODE = '22023';
  END IF;
  FOR r IN SELECT j.id, j.owner_id, j.attempt, j.max_attempts, j.cancel_requested_at
             FROM public.jobs j
            WHERE j.state = 'running' AND j.lease_expires_at < now()
            ORDER BY j.lease_expires_at
            LIMIT p_limit
              FOR UPDATE SKIP LOCKED LOOP
    BEGIN
      v_state := CASE WHEN r.cancel_requested_at IS NOT NULL THEN 'cancelled'
                      WHEN r.attempt < r.max_attempts THEN 'queued'
                      ELSE 'failed' END;
      v_at := now() + make_interval(secs => least(30 * power(2, greatest(r.attempt, 1) - 1), 900)
                                            * (0.8 + 0.4 * random()));
      UPDATE public.jobs j
         SET state = v_state,
             error_category = CASE WHEN v_state = 'failed' THEN 'lease_lost' END,
             available_at = CASE WHEN v_state = 'queued' THEN v_at ELSE j.available_at END,
             finished_at = CASE WHEN v_state = 'queued' THEN NULL ELSE now() END,
             lease_version = j.lease_version + 1, next_seq = j.next_seq + 1,
             leased_by = NULL, lease_expires_at = NULL, heartbeat_at = NULL, updated_at = now()
       WHERE j.id = r.id AND j.state = 'running'
      RETURNING j.lease_version, j.next_seq INTO v_version, v_seq;
      INSERT INTO public.job_events (owner_id, job_id, seq, kind, payload, lease_version)
      VALUES (r.owner_id, r.id, v_seq,
              CASE v_state WHEN 'queued' THEN 'retry_scheduled' ELSE v_state END,
              CASE v_state
                WHEN 'queued' THEN jsonb_build_object('category', 'lease_lost', 'available_at', v_at)
                WHEN 'failed' THEN jsonb_build_object('category', 'lease_lost')
                ELSE '{}'::jsonb END,
              v_version);
      PERFORM pg_notify('job_events', r.id::text);
      v_done := v_done + 1;
    EXCEPTION WHEN OTHERS THEN
      NULL; -- skipped; it cannot block other rows
    END;
  END LOOP;
  FOR r IN SELECT j.id, j.owner_id
             FROM public.jobs j
            WHERE j.state = 'queued' AND j.attempt >= j.max_attempts
            ORDER BY j.available_at
            LIMIT p_limit
              FOR UPDATE SKIP LOCKED LOOP
    BEGIN
      UPDATE public.jobs j
         SET state = 'failed', error_category = 'internal', finished_at = now(),
             next_seq = j.next_seq + 1, updated_at = now()
       WHERE j.id = r.id AND j.state = 'queued'
      RETURNING j.lease_version, j.next_seq INTO v_version, v_seq;
      INSERT INTO public.job_events (owner_id, job_id, seq, kind, payload, lease_version)
      VALUES (r.owner_id, r.id, v_seq, 'failed', jsonb_build_object('category', 'internal'),
              v_version);
      PERFORM pg_notify('job_events', r.id::text);
      v_done := v_done + 1;
    EXCEPTION WHEN OTHERS THEN
      NULL;
    END;
  END LOOP;
  RETURN v_done;
END $$;

-- Counts only, never ids: jobs per state.
CREATE OR REPLACE FUNCTION public.queue_stats()
  RETURNS TABLE (metric text, total bigint)
  LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, pg_temp
AS $$
#variable_conflict use_column
BEGIN
  RETURN QUERY
    SELECT 'jobs_' || s.state, (SELECT count(*) FROM public.jobs j WHERE j.state = s.state)
      FROM unnest(ARRAY['queued', 'running', 'completed', 'failed', 'cancelled'])
           WITH ORDINALITY AS s(state, n)
     ORDER BY s.n;
END $$;

-- Owner, ACL and version of each function. Every grantee but the owner is revoked first, so the
-- ACL ends exactly {ownvitals_queue=X/ownvitals_queue, ownvitals_app=X/ownvitals_queue}.
DO $$
DECLARE
  f text;
  g record;
BEGIN
  FOREACH f IN ARRAY ARRAY['public.queue_claim(text,integer,text[])', 'public.queue_reap(integer)',
                           'public.queue_stats()'] LOOP
    EXECUTE format('ALTER FUNCTION %s OWNER TO ownvitals_queue', f);
    EXECUTE format('REVOKE ALL ON FUNCTION %s FROM PUBLIC', f);
    FOR g IN SELECT DISTINCT
                    CASE WHEN a.grantee = 0 THEN 'PUBLIC' ELSE a.grantee::regrole::text END
                      AS grantee,
                    a.grantor::regrole::text AS grantor
               FROM pg_catalog.pg_proc p, aclexplode(p.proacl) a
              WHERE p.oid = f::regprocedure AND a.grantee <> p.proowner LOOP
      EXECUTE format('SET LOCAL ROLE %s', g.grantor);
      EXECUTE format('REVOKE ALL ON FUNCTION %s FROM %s CASCADE', f, g.grantee);
      EXECUTE 'RESET ROLE';
    END LOOP;
    EXECUTE format('GRANT EXECUTE ON FUNCTION %s TO ownvitals_queue', f);
    EXECUTE format('GRANT EXECUTE ON FUNCTION %s TO ownvitals_app', f);
    EXECUTE format('COMMENT ON FUNCTION %s IS %L', f, 'ownvitals-queue v1');
  END LOOP;
END $$;
