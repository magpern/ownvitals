-- No user code may run as ownvitals_queue (ADR 0005 section 3): no other user function,
-- operator, trigger or rule, and no expression calling a built-in that runs SQL text or changes
-- settings. The queue check (ownvitals.db.queue_check) refuses the same: stop here, naming each
-- object as it and guard 9 do. ensure_month_partitions, webhook_secrets_apply,
-- webhook_event_insert and webhook_events_purge_owner (40-withings.sql), and
-- withings_rate_claim, withings_rate_release and withings_rate_pause (rate.sql), and
-- mail_outbox_claim, mail_outbox_mark and owner_notice_queue (50-outbox.sql, #194), are
-- admitted here by name, and no other function is.
-- Their bodies are pinned by digest with the queue functions (ownvitals/db/queue_digests.py;
-- the outbox's in ownvitals/db/outbox_digests.py).
DO $$
DECLARE
  v_found text;
BEGIN
  SELECT string_agg(x.what, ', ' ORDER BY x.what) INTO v_found FROM (
    SELECT 'function ' || n.nspname || '.' || p.proname || '('
           || pg_catalog.oidvectortypes(p.proargtypes) || ')' AS what
      FROM pg_catalog.pg_proc p JOIN pg_catalog.pg_namespace n ON n.oid = p.pronamespace
     WHERE NOT (n.nspname = 'public' AND p.proname IN ('queue_claim', 'queue_reap', 'queue_stats',
            'queue_enqueue', 'queue_cancel_for_secret', 'queue_replay', 'queue_schedule',
            'ensure_month_partitions', 'webhook_secrets_apply', 'webhook_event_insert',
            'webhook_events_purge_owner',
            'withings_rate_claim', 'withings_rate_release', 'withings_rate_pause',
            'mail_outbox_claim', 'mail_outbox_mark', 'owner_notice_queue'))
       AND (p.oid >= 16384 OR n.nspname = 'public'
            OR (n.nspname NOT IN ('pg_catalog', 'information_schema', 'pg_toast')
                AND n.nspname !~ '^pg_(toast_)?temp_[0-9]+$'))
    UNION ALL
    SELECT 'operator ' || n.nspname || '.' || o.oprname || '('
           || CASE WHEN o.oprleft = 0 THEN 'NONE' ELSE o.oprleft::regtype::text END || ', '
           || CASE WHEN o.oprright = 0 THEN 'NONE' ELSE o.oprright::regtype::text END || ')'
      FROM pg_catalog.pg_operator o JOIN pg_catalog.pg_namespace n ON n.oid = o.oprnamespace
     WHERE o.oid >= 16384 OR n.nspname = 'public'
        OR (n.nspname NOT IN ('pg_catalog', 'information_schema', 'pg_toast')
            AND n.nspname !~ '^pg_(toast_)?temp_[0-9]+$')
    UNION ALL
    SELECT 'trigger ' || t.tgname || ' on ' || n.nspname || '.' || c.relname
      FROM pg_catalog.pg_trigger t JOIN pg_catalog.pg_class c ON c.oid = t.tgrelid
      JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace WHERE NOT t.tgisinternal
    UNION ALL
    SELECT 'rule ' || w.rulename || ' on ' || n.nspname || '.' || c.relname
      FROM pg_catalog.pg_rewrite w JOIN pg_catalog.pg_class c ON c.oid = w.ev_class
      JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
     WHERE w.oid >= 16384 AND w.rulename <> '_RETURN'
    UNION SELECT 'built-in ' || f.proname || ' in ' || e.what FROM (
      SELECT 'the default of ' || n.nspname || '.' || c.relname || '.' || a.attname AS what,
             d.adbin::text AS tree
        FROM pg_catalog.pg_attrdef d JOIN pg_catalog.pg_class c ON c.oid = d.adrelid
        JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
        JOIN pg_catalog.pg_attribute a ON a.attrelid = d.adrelid AND a.attnum = d.adnum
      UNION ALL
      SELECT 'constraint ' || k.conname || ' on ' || n.nspname || '.'
             || coalesce(c.relname, y.typname), k.conbin::text
        FROM pg_catalog.pg_constraint k JOIN pg_catalog.pg_namespace n ON n.oid = k.connamespace
        LEFT JOIN pg_catalog.pg_class c ON c.oid = k.conrelid
        LEFT JOIN pg_catalog.pg_type y ON y.oid = k.contypid WHERE k.conbin IS NOT NULL
      UNION ALL
      SELECT 'index ' || n.nspname || '.' || c.relname, concat(i.indexprs::text, i.indpred::text)
        FROM pg_catalog.pg_index i JOIN pg_catalog.pg_class c ON c.oid = i.indexrelid
        JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
      UNION ALL
      SELECT 'the default of type ' || n.nspname || '.' || y.typname, y.typdefaultbin::text
        FROM pg_catalog.pg_type y JOIN pg_catalog.pg_namespace n ON n.oid = y.typnamespace
      UNION ALL
      SELECT 'the partition key of ' || n.nspname || '.' || c.relname, x.partexprs::text
        FROM pg_catalog.pg_partitioned_table x JOIN pg_catalog.pg_class c ON c.oid = x.partrelid
        JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
    ) e
    CROSS JOIN LATERAL pg_catalog.regexp_matches(e.tree, '[:]funcid ([0-9]+)', 'g') m
    JOIN pg_catalog.pg_proc f ON f.oid = m[1]::oid
    WHERE f.pronamespace = 'pg_catalog'::regnamespace AND f.proname IN ('query_to_xml',
      'query_to_xmlschema', 'query_to_xml_and_xmlschema', 'cursor_to_xml', 'cursor_to_xmlschema',
      'table_to_xml', 'table_to_xmlschema', 'table_to_xml_and_xmlschema', 'schema_to_xml',
      'schema_to_xmlschema', 'schema_to_xml_and_xmlschema', 'database_to_xml',
      'database_to_xmlschema', 'database_to_xml_and_xmlschema', 'ts_stat', 'ts_rewrite',
      'set_config')) x;
  IF v_found IS NOT NULL THEN
    RAISE EXCEPTION 'the database holds % besides the queue functions; drop them by hand '
      '(ADR 0005 section 3)', v_found;
  END IF;
END $$;

-- Claim the next queued job of one of p_kinds whose attempts are not spent. A row whose update
-- fails is skipped (and stays locked until this transaction ends), so it cannot stall the queue.
CREATE OR REPLACE FUNCTION public.queue_claim(p_worker text, p_lease_seconds integer,
                                              p_kinds text[])
  RETURNS TABLE (job_id uuid, owner_id uuid, lease_version bigint)
  LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, pg_temp
AS $$
#variable_conflict use_column
DECLARE
  v_skipped uuid[] := '{}';
  v_id uuid;
  v_owner uuid;
  v_version bigint;
  v_seq bigint;
  v_attempt integer;
BEGIN
  IF p_worker IS NULL OR p_worker !~ '^[A-Za-z0-9._:-]{1,100}$' THEN
    RAISE EXCEPTION 'invalid worker id' USING ERRCODE = '22023';
  END IF;
  IF p_lease_seconds IS NULL OR p_lease_seconds < 30 OR p_lease_seconds > 600 THEN
    RAISE EXCEPTION 'p_lease_seconds must be 30 to 600' USING ERRCODE = '22023';
  END IF;
  IF p_kinds IS NULL OR cardinality(p_kinds) = 0 THEN
    RETURN;
  END IF;
  FOR i IN 1..10 LOOP
    SELECT j.id, j.owner_id INTO v_id, v_owner
      FROM public.jobs j
     WHERE j.state = 'queued' AND j.available_at <= now() AND j.attempt < j.max_attempts
       AND j.kind = ANY (p_kinds) AND j.id <> ALL (v_skipped)
       AND NOT (j.lane = 5 AND EXISTS (
             SELECT 1 FROM public.jobs r
              WHERE r.owner_id = j.owner_id AND r.state = 'running' AND r.lane = 5))
     ORDER BY j.lane,
              (SELECT count(*) FROM public.jobs r
                WHERE r.owner_id = j.owner_id AND r.state = 'running'),
              j.available_at, j.created_at
     LIMIT 1
       FOR UPDATE SKIP LOCKED;
    IF NOT FOUND THEN
      RETURN;
    END IF;
    BEGIN
      UPDATE public.jobs j
         SET state = 'running', attempt = j.attempt + 1, lease_version = j.lease_version + 1,
             leased_by = p_worker, lease_expires_at = now() + make_interval(secs => p_lease_seconds),
             heartbeat_at = now(), started_at = coalesce(j.started_at, now()),
             next_seq = j.next_seq + 1, updated_at = now()
       WHERE j.id = v_id
      RETURNING j.lease_version, j.next_seq, j.attempt INTO v_version, v_seq, v_attempt;
      INSERT INTO public.job_events (owner_id, job_id, seq, kind, payload, lease_version)
      VALUES (v_owner, v_id, v_seq, 'claimed', jsonb_build_object('attempt', v_attempt),
              v_version);
      PERFORM pg_notify('job_events', v_id::text);
    EXCEPTION WHEN OTHERS THEN
      v_skipped := v_skipped || v_id;
      CONTINUE;
    END;
    job_id := v_id;
    owner_id := v_owner;
    lease_version := v_version;
    RETURN NEXT;
    RETURN;
  END LOOP;
END $$;

-- Running jobs whose lease expired: the token goes up (fencing the old holder), then cancelled
-- if a cancel was requested, queued with backoff while attempts remain, else dead_letter with
-- lease_lost (a retryable budget that is spent; ADR 0005 section 8). Queued rows with spent
-- attempts (should not exist) fail as internal, which is not retryable. A bad row is skipped.
CREATE OR REPLACE FUNCTION public.queue_reap(p_limit integer)
  RETURNS integer
  LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, pg_temp
AS $$
DECLARE
  r record;
  v_done integer := 0;
  v_state text;
  v_at timestamptz;
  v_version bigint;
  v_seq bigint;
BEGIN
  IF p_limit IS NULL OR p_limit < 1 OR p_limit > 100 THEN
    RAISE EXCEPTION 'p_limit must be 1 to 100' USING ERRCODE = '22023';
  END IF;
  FOR r IN SELECT j.id, j.owner_id, j.attempt, j.max_attempts, j.cancel_requested_at
             FROM public.jobs j
            WHERE j.state = 'running' AND j.lease_expires_at < now()
            ORDER BY j.lease_expires_at
            LIMIT p_limit
              FOR UPDATE SKIP LOCKED LOOP
    BEGIN
      v_state := CASE WHEN r.cancel_requested_at IS NOT NULL THEN 'cancelled'
                      WHEN r.attempt < r.max_attempts THEN 'queued'
                      ELSE 'dead_letter' END;
      v_at := now() + make_interval(secs => least(30 * power(2, greatest(r.attempt, 1) - 1), 900)
                                            * (0.8 + 0.4 * random()));
      UPDATE public.jobs j
         SET state = v_state,
             error_category = CASE WHEN v_state = 'dead_letter' THEN 'lease_lost' END,
             available_at = CASE WHEN v_state = 'queued' THEN v_at ELSE j.available_at END,
             finished_at = CASE WHEN v_state = 'queued' THEN NULL ELSE now() END,
             lease_version = j.lease_version + 1, next_seq = j.next_seq + 1,
             leased_by = NULL, lease_expires_at = NULL, heartbeat_at = NULL, updated_at = now()
       WHERE j.id = r.id AND j.state = 'running'
      RETURNING j.lease_version, j.next_seq INTO v_version, v_seq;
      INSERT INTO public.job_events (owner_id, job_id, seq, kind, payload, lease_version)
      VALUES (r.owner_id, r.id, v_seq,
              CASE v_state WHEN 'queued' THEN 'retry_scheduled' ELSE v_state END,
              CASE v_state
                WHEN 'queued' THEN jsonb_build_object('category', 'lease_lost', 'available_at', v_at)
                WHEN 'dead_letter' THEN jsonb_build_object('category', 'lease_lost')
                ELSE '{}'::jsonb END,
              v_version);
      PERFORM pg_notify('job_events', r.id::text);
      v_done := v_done + 1;
    EXCEPTION WHEN OTHERS THEN
      NULL; -- skipped; it cannot block other rows
    END;
  END LOOP;
  FOR r IN SELECT j.id, j.owner_id
             FROM public.jobs j
            WHERE j.state = 'queued' AND j.attempt >= j.max_attempts
            ORDER BY j.available_at
            LIMIT p_limit
              FOR UPDATE SKIP LOCKED LOOP
    BEGIN
      UPDATE public.jobs j
         SET state = 'failed', error_category = 'internal', finished_at = now(),
             next_seq = j.next_seq + 1, updated_at = now()
       WHERE j.id = r.id AND j.state = 'queued'
      RETURNING j.lease_version, j.next_seq INTO v_version, v_seq;
      INSERT INTO public.job_events (owner_id, job_id, seq, kind, payload, lease_version)
      VALUES (r.owner_id, r.id, v_seq, 'failed', jsonb_build_object('category', 'internal'),
              v_version);
      PERFORM pg_notify('job_events', r.id::text);
      v_done := v_done + 1;
    EXCEPTION WHEN OTHERS THEN
      NULL;
    END;
  END LOOP;
  RETURN v_done;
END $$;

-- Counts only, never ids: jobs per state.
CREATE OR REPLACE FUNCTION public.queue_stats()
  RETURNS TABLE (metric text, total bigint)
  LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, pg_temp
AS $$
#variable_conflict use_column
BEGIN
  RETURN QUERY
    SELECT 'jobs_' || s.state, (SELECT count(*) FROM public.jobs j WHERE j.state = s.state)
      FROM unnest(ARRAY['queued', 'running', 'completed', 'failed', 'dead_letter', 'cancelled'])
           WITH ORDINALITY AS s(state, n)
     ORDER BY s.n;
END $$;

-- Enqueue one webhook or scheduler job owned by the connection's owner (ADR 0005 section 8).
-- The advisory lock is namespace 1, job creation, keyed by the owner (ADR 0005 section 9).
-- A queued singleton collapses into the existing row and its available_at moves 30 seconds out.
-- A running singleton gets exactly one queued follow-up; a later enqueue collapses into that.
CREATE OR REPLACE FUNCTION public.queue_enqueue(
    p_connection_id uuid, p_kind text, p_origin text, p_input jsonb,
    p_singleton_key text, p_max_attempts integer, p_target_secret_id uuid)
  RETURNS uuid
  LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, pg_temp
AS $$
DECLARE
  v_owner uuid;
  v_lane smallint;
  v_id uuid;
  v_existing uuid;
BEGIN
  IF p_connection_id IS NULL OR p_kind IS NULL OR p_kind !~ '^[a-z_]{1,40}$' THEN
    RAISE EXCEPTION 'invalid enqueue' USING ERRCODE = '22023';
  END IF;
  IF p_origin IS NULL OR p_origin NOT IN ('webhook', 'scheduler') THEN
    RAISE EXCEPTION 'invalid origin' USING ERRCODE = '22023';
  END IF;
  IF p_input IS NULL OR pg_catalog.jsonb_typeof(p_input) <> 'object'
     OR pg_catalog.octet_length(p_input::text) > 16384 THEN
    RAISE EXCEPTION 'invalid input' USING ERRCODE = '22023';
  END IF;
  IF p_singleton_key IS NOT NULL AND p_singleton_key !~ '^[a-z0-9_:-]{1,80}$' THEN
    RAISE EXCEPTION 'invalid singleton key' USING ERRCODE = '22023';
  END IF;
  IF p_max_attempts IS NULL OR p_max_attempts < 1 OR p_max_attempts > 10 THEN
    RAISE EXCEPTION 'invalid max_attempts' USING ERRCODE = '22023';
  END IF;
  SELECT c.owner_id INTO v_owner FROM public.connections c
   WHERE c.id = p_connection_id AND c.status <> 'disconnected';
  IF NOT FOUND THEN
    RAISE EXCEPTION 'unknown connection' USING ERRCODE = '22023';
  END IF;
  PERFORM pg_catalog.pg_advisory_xact_lock(1, pg_catalog.hashtext(v_owner::text));
  v_lane := CASE
    WHEN p_kind = 'withings_backfill' THEN 5
    WHEN p_kind = 'withings_reconcile' THEN 4
    WHEN p_kind = 'withings_poll' THEN 3
    WHEN p_origin = 'webhook' THEN 2
    ELSE 3 END;
  IF p_singleton_key IS NOT NULL THEN
    SELECT j.id INTO v_existing FROM public.jobs j
     WHERE j.owner_id = v_owner AND j.singleton_key = p_singleton_key AND j.state = 'queued'
       FOR UPDATE;
    IF FOUND THEN
      UPDATE public.jobs j
         SET available_at = now() + make_interval(secs => 30), updated_at = now()
       WHERE j.id = v_existing;
      RETURN v_existing;
    END IF;
  END IF;
  v_id := pg_catalog.gen_random_uuid();
  INSERT INTO public.jobs (
      id, owner_id, kind, origin, lane, state, input, singleton_key, target_secret_id,
      max_attempts, next_seq)
  VALUES (
      v_id, v_owner, p_kind, p_origin, v_lane, 'queued', p_input, p_singleton_key,
      p_target_secret_id, p_max_attempts, 1);
  INSERT INTO public.job_events (owner_id, job_id, seq, kind, payload, lease_version)
  VALUES (v_owner, v_id, 1, 'queued', '{}'::jsonb, 0);
  PERFORM pg_catalog.pg_notify('job_events', v_id::text);
  PERFORM pg_catalog.pg_notify('jobs_queued', '');
  RETURN v_id;
END $$;

-- Cancel queued jobs of one kind that target a webhook secret, across owners (ADR 0008, ADR
-- 0005 section 3). Returns how many were cancelled. A job already claimed is left running; it
-- re-checks the target when it runs.
CREATE OR REPLACE FUNCTION public.queue_cancel_for_secret(p_kind text, p_secret_id uuid)
  RETURNS integer
  LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, pg_temp
AS $$
DECLARE
  r record;
  v_done integer := 0;
  v_version bigint;
  v_seq bigint;
BEGIN
  IF p_kind IS NULL OR p_kind !~ '^[a-z_]{1,40}$' OR p_secret_id IS NULL THEN
    RAISE EXCEPTION 'invalid cancel' USING ERRCODE = '22023';
  END IF;
  FOR r IN SELECT j.id, j.owner_id FROM public.jobs j
            WHERE j.state = 'queued' AND j.kind = p_kind AND j.target_secret_id = p_secret_id
            ORDER BY j.created_at
              FOR UPDATE SKIP LOCKED LOOP
    BEGIN
      UPDATE public.jobs j
         SET state = 'cancelled',
             cancel_requested_at = coalesce(j.cancel_requested_at, now()),
             finished_at = now(), next_seq = j.next_seq + 1, updated_at = now()
       WHERE j.id = r.id AND j.state = 'queued'
      RETURNING j.lease_version, j.next_seq INTO v_version, v_seq;
      IF NOT FOUND THEN
        CONTINUE;
      END IF;
      INSERT INTO public.job_events (owner_id, job_id, seq, kind, payload, lease_version)
      VALUES (r.owner_id, r.id, v_seq, 'cancelled', '{}'::jsonb, v_version);
      PERFORM pg_catalog.pg_notify('job_events', r.id::text);
      v_done := v_done + 1;
    EXCEPTION WHEN OTHERS THEN
      NULL;
    END;
  END LOOP;
  RETURN v_done;
END $$;

-- A new queued job from a dead-lettered one. The terminal row is not changed (ADR 0005 section 8).
CREATE OR REPLACE FUNCTION public.queue_replay(p_job_id uuid)
  RETURNS TABLE (job_id uuid, owner_id uuid)
  LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, pg_temp
AS $$
#variable_conflict use_column
DECLARE
  v_owner uuid;
  v_kind text;
  v_input jsonb;
  v_lane smallint;
  v_singleton text;
  v_max integer;
  v_secret uuid;
  v_state text;
  v_id uuid;
BEGIN
  IF p_job_id IS NULL THEN
    RAISE EXCEPTION 'invalid replay' USING ERRCODE = '22023';
  END IF;
  SELECT j.owner_id, j.kind, j.input, j.lane, j.singleton_key, j.max_attempts,
         j.target_secret_id, j.state
    INTO v_owner, v_kind, v_input, v_lane, v_singleton, v_max, v_secret, v_state
    FROM public.jobs j WHERE j.id = p_job_id FOR UPDATE;
  IF NOT FOUND OR v_state <> 'dead_letter' THEN
    RAISE EXCEPTION 'not replayable' USING ERRCODE = '22023';
  END IF;
  v_id := pg_catalog.gen_random_uuid();
  BEGIN
    INSERT INTO public.jobs (
        id, owner_id, kind, origin, lane, state, input, singleton_key, target_secret_id,
        max_attempts, next_seq)
    VALUES (
        v_id, v_owner, v_kind, 'operator', v_lane, 'queued', v_input, v_singleton, v_secret,
        v_max, 1);
  EXCEPTION WHEN unique_violation THEN
    RAISE EXCEPTION 'already queued' USING ERRCODE = '22023';
  END;
  INSERT INTO public.job_events (owner_id, job_id, seq, kind, payload, lease_version)
  VALUES (v_owner, v_id, 1, 'queued', '{}'::jsonb, 0);
  PERFORM pg_catalog.pg_notify('job_events', v_id::text);
  PERFORM pg_catalog.pg_notify('jobs_queued', '');
  job_id := v_id;
  owner_id := v_owner;
  RETURN NEXT;
END $$;

-- The scheduler (PLAN section 4.4, ADR 0002 section 4, ADR 0005 section 8): one job of p_kind
-- for every connected connection that has none queued or running and none created in the last
-- p_interval_seconds. Only the poll and the reconciliation are scheduled. Each job is created by
-- queue_enqueue (origin scheduler) and gets its context only when claimed. At most 500 per call;
-- the rest stay due for the next call. Returns the count, never an owner or a connection id.
CREATE OR REPLACE FUNCTION public.queue_schedule(p_kind text, p_interval_seconds integer)
  RETURNS integer
  LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, pg_temp
AS $$
DECLARE
  r record;
  v_done integer := 0;
BEGIN
  IF p_kind IS NULL OR p_kind NOT IN ('withings_poll', 'withings_reconcile') THEN
    RAISE EXCEPTION 'invalid schedule' USING ERRCODE = '22023';
  END IF;
  IF p_interval_seconds IS NULL OR p_interval_seconds < 3600
     OR p_interval_seconds > 604800 THEN
    RAISE EXCEPTION 'invalid interval' USING ERRCODE = '22023';
  END IF;
  FOR r IN SELECT c.id, c.owner_id FROM public.connections c
            WHERE c.status = 'connected' ORDER BY c.id LOOP
    -- The same lock as queue_enqueue's, taken first so the check and the insert are one step.
    PERFORM pg_catalog.pg_advisory_xact_lock(1, pg_catalog.hashtext(r.owner_id::text));
    IF EXISTS (SELECT FROM public.jobs j
                WHERE j.owner_id = r.owner_id AND j.kind = p_kind
                  AND j.input ->> 'connection_id' = r.id::text
                  AND (j.state IN ('queued', 'running')
                       OR j.created_at > now() - make_interval(secs => p_interval_seconds))) THEN
      CONTINUE;
    END IF;
    PERFORM public.queue_enqueue(
      r.id, p_kind, 'scheduler', pg_catalog.jsonb_build_object('connection_id', r.id),
      NULL, 3, NULL);
    v_done := v_done + 1;
    EXIT WHEN v_done >= 500;
  END LOOP;
  RETURN v_done;
END $$;

-- Owner, ACL and version of each function. Every grantee but the owner is revoked first, so the
-- ACL ends exactly {ownvitals_queue=X/ownvitals_queue, ownvitals_app=X/ownvitals_queue}.
DO $$
DECLARE
  f text;
  g record;
BEGIN
  FOREACH f IN ARRAY ARRAY[
      'public.queue_claim(text,integer,text[])', 'public.queue_reap(integer)',
      'public.queue_stats()',
      'public.queue_enqueue(uuid,text,text,jsonb,text,integer,uuid)',
      'public.queue_cancel_for_secret(text,uuid)', 'public.queue_replay(uuid)',
      'public.queue_schedule(text,integer)'] LOOP
    EXECUTE format('ALTER FUNCTION %s OWNER TO ownvitals_queue', f);
    EXECUTE format('REVOKE ALL ON FUNCTION %s FROM PUBLIC', f);
    FOR g IN SELECT DISTINCT
                    CASE WHEN a.grantee = 0 THEN 'PUBLIC' ELSE a.grantee::regrole::text END
                      AS grantee,
                    a.grantor::regrole::text AS grantor
               FROM pg_catalog.pg_proc p, aclexplode(p.proacl) a
              WHERE p.oid = f::regprocedure AND a.grantee <> p.proowner LOOP
      EXECUTE format('SET LOCAL ROLE %s', g.grantor);
      EXECUTE format('REVOKE ALL ON FUNCTION %s FROM %s CASCADE', f, g.grantee);
      EXECUTE 'RESET ROLE';
    END LOOP;
    EXECUTE format('GRANT EXECUTE ON FUNCTION %s TO ownvitals_queue', f);
    EXECUTE format('GRANT EXECUTE ON FUNCTION %s TO ownvitals_app', f);
    EXECUTE format('COMMENT ON FUNCTION %s IS %L', f, 'ownvitals-queue v2');
  END LOOP;
END $$;
