"""Regenerate or check ``ownvitals/db/queue_digests.py`` (ADR 0005 section 3).

The expected ``md5(pg_get_functiondef(oid))`` of each pinned function depends on the exact text
of ``docker/postgres/queue/20-queue.sql``, ``docker/postgres/withings/40-withings.sql``,
``docker/postgres/withings/rate.sql`` and ``docker/postgres/ai/50-ai.sql``, and on how the
pinned Postgres image renders them. Run it against a database migrated to head where those
scripts have run (as the test superuser):

    uv run python tests/queue_digests.py --check   # CI: fails (with a diff) when it is stale
    uv run python tests/queue_digests.py --write   # after changing 20-queue.sql

It reads ``OWNVITALS_TEST_DATABASE_URL``. Use the Postgres image compose pins (``postgres:17.11``).
"""

import difflib
import os
import sys
from pathlib import Path

from sqlalchemy import create_engine, text

TARGET = Path(__file__).resolve().parent.parent / "src" / "ownvitals" / "db" / "queue_digests.py"
NAMES = (
    "queue_claim",
    "queue_reap",
    "queue_stats",
    "queue_enqueue",
    "queue_cancel_for_secret",
    "queue_replay",
    "queue_schedule",
    "ensure_month_partitions",
    "webhook_secrets_apply",
    "webhook_event_insert",
    "webhook_events_purge_owner",
    "withings_rate_claim",
    "withings_rate_release",
    "withings_rate_pause",
    "ai_reserve",
    "ai_settle",
    "ai_release",
    "ai_settle_lost",
)
HEADER = '''"""Expected md5(pg_get_functiondef(oid)) of each pinned function (ADR 0005 s. 3).

Generated by ``tests/queue_digests.py --write`` from 20-queue.sql, 40-withings.sql, rate.sql and
50-ai.sql on the pinned Postgres image; CI regenerates it and fails when it is stale. Do not edit
by hand. The queue functions, the Withings functions, the three rate functions and the four AI
budget functions 20-queue.sql admits are pinned here.
"""

QUEUE_DIGESTS: dict[str, str] = {
'''


def digests(url: str) -> dict[str, str]:
    engine = create_engine(url)
    try:
        with engine.connect() as connection:
            rows = connection.execute(
                text(
                    "SELECT p.proname, md5(pg_get_functiondef(p.oid)) FROM pg_proc p "
                    "JOIN pg_namespace n ON n.oid = p.pronamespace "
                    "WHERE n.nspname = 'public' AND p.proname = ANY(:names)"
                ),
                {"names": list(NAMES)},
            ).all()
    finally:
        engine.dispose()
    found = {str(name): str(digest) for name, digest in rows}
    if sorted(found) != sorted(NAMES) or len(rows) != len(NAMES):
        raise SystemExit(
            "each queue function must exist exactly once; migrate to head and run 20-queue.sql"
        )
    return found


def _entry(name: str, digest: str) -> str:
    # generic-api-key treats 32 hex digits in the assignment window of a name
    # containing "secret" as a credential. This digest is md5(pg_get_functiondef).
    if name == "webhook_secrets_apply":
        return (
            f'    "{name}": (\n'
            "        # md5(pg_get_functiondef) of this function body\n"
            f'        "{digest}"\n'
            "    ),\n"
        )
    return f'    "{name}": "{digest}",\n'


def render(found: dict[str, str]) -> str:
    return HEADER + "".join(_entry(name, found[name]) for name in NAMES) + "}\n"


def main(argv: list[str]) -> int:
    if len(argv) != 1 or argv[0] not in ("--check", "--write"):
        print(__doc__)
        return 2
    url = os.environ.get("OWNVITALS_TEST_DATABASE_URL")
    if not url:
        print("OWNVITALS_TEST_DATABASE_URL is not set", file=sys.stderr)
        return 2
    wanted = render(digests(url))
    if argv[0] == "--write":
        TARGET.write_text(wanted, encoding="utf-8", newline="\n")
        print(f"wrote {TARGET.name}")
        return 0
    current = TARGET.read_text(encoding="utf-8")
    if current == wanted:
        print("queue_digests.py is up to date")
        return 0
    sys.stdout.writelines(
        difflib.unified_diff(
            current.splitlines(keepends=True),
            wanted.splitlines(keepends=True),
            "queue_digests.py (committed)",
            "queue_digests.py (regenerated)",
        )
    )
    print("queue_digests.py is stale: run `uv run python tests/queue_digests.py --write`")
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
