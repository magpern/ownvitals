"""The seeded conditions of ADR 0006's test specification (``0006-ecg-subsystem-tests.md``).

SYNTHETIC: every strip is generated by ``ecgsynth`` and the noise models of ``ecgnoise``. A case
is ``(condition, sampling rate, seed index, seed count, band)``; the heart rate of a sinus
condition walks the band (40-180 bpm, or 40-49.9 bpm for the low band) over the seed indices, so
a set of 20 seeds covers the whole band, both ends included. Results are cached for the
session: the gate, beat-matching and HR/HRV tests share one analysis of each strip.
"""

import zlib
from collections.abc import Callable
from dataclasses import dataclass
from functools import cache

import ecgnoise
import numpy as np

from ecgsynth import Strip, make_strip
from ownvitals.ecg.pipeline import Result, analyse

SYNTHETIC = True

RATES = (300, 500)
N_SEEDS = 20  # per condition and rate, in CI (the specification asks for at least 20)
FULL_BAND = (40.0, 180.0)  # bpm
LOW_BAND = (40.0, 49.9)  # "below 50 bpm" (amended 2026-10-31, #40)
HIGH_BAND = (50.0, 180.0)

Band = tuple[float, float]
Builder = Callable[[int, int, int, Band], Strip]  # (index, sampling rate, count, band) -> strip


def sinus_hr(index: int, count: int = N_SEEDS, band: Band = FULL_BAND) -> float:
    """The heart rate of seed ``index``: evenly spread over the band, ends included."""
    low, high = band
    return float(low + (high - low) * index / (count - 1))


def af_hr(index: int, count: int = N_SEEDS) -> float:
    """AF-like strips run at 100-150 bpm."""
    return float(100.0 + 50.0 * index / (count - 1))


def noise_rng(condition: str, index: int, fs: int) -> np.random.Generator:
    return np.random.default_rng([index, zlib.crc32(condition.encode()), fs])


def _clean(index: int, fs: int, count: int, band: Band, **options: object) -> Strip:
    return make_strip(index, sinus_hr(index, count, band), fs, **options)  # type: ignore[arg-type]


def _white(snr_db: float) -> Builder:
    def build(index: int, fs: int, count: int, band: Band) -> Strip:
        strip = _clean(index, fs, count, band)
        rng = noise_rng(f"white{snr_db}", index, fs)
        return ecgnoise.noisy(strip, ecgnoise.white(rng, strip, snr_db))

    return build


def _emg(index: int, fs: int, count: int, band: Band) -> Strip:
    strip = _clean(index, fs, count, band)
    return ecgnoise.noisy(strip, ecgnoise.emg_like(noise_rng("emg6", index, fs), strip, 6.0))


def _wander(index: int, fs: int, count: int, band: Band) -> Strip:
    strip = _clean(index, fs, count, band)
    return ecgnoise.noisy(strip, ecgnoise.baseline_wander(noise_rng("wander", index, fs), strip))


def _mains(index: int, fs: int, count: int, band: Band) -> Strip:
    strip = _clean(index, fs, count, band)
    nominal = 50.0 if index % 2 == 0 else 60.0
    return ecgnoise.noisy(strip, ecgnoise.mains(noise_rng("mains", index, fs), strip, nominal))


def _low_amplitude(index: int, fs: int, count: int, band: Band) -> Strip:
    return _clean(index, fs, count, band, amplitude_mv=0.3)


def _inverted(index: int, fs: int, count: int, band: Band) -> Strip:
    return _clean(index, fs, count, band, polarity=-1)


def _af(index: int, fs: int, count: int, band: Band) -> Strip:
    return make_strip(index, af_hr(index, count), fs, kind="af")


def _ectopic(index: int, fs: int, count: int, band: Band) -> Strip:
    return _clean(index, fs, count, band, kind="ectopic", n_ectopic=1 + index % 2)


def _respiratory(index: int, fs: int, count: int, band: Band) -> Strip:
    """Respiratory modulation of +-12 % at 0.25 Hz, 55-180 bpm (where only the first interval
    can be excluded)."""
    return make_strip(index, sinus_hr(index, count, (55.0, 180.0)), fs, kind="respiratory")


def _respiratory_slow(index: int, fs: int, count: int, band: Band) -> Strip:
    """The same at 40 and 45 bpm (alternating), where section 8's 20 % rule drops real
    intervals."""
    return make_strip(index, 40.0 if index % 2 == 0 else 45.0, fs, kind="respiratory")


def _motion_edge(index: int, fs: int, count: int, band: Band) -> Strip:
    """One burst of 1-3 s at 0 dB at the start (even index) or the end (odd index)."""
    strip = _clean(index, fs, count, band)
    rng = noise_rng("motion_edge", index, fs)
    length = float(rng.uniform(1.0, 3.0))
    start = 0.0 if index % 2 == 0 else 30.0 - length
    return ecgnoise.noisy(strip, ecgnoise.motion_burst(rng, strip, start, length, 0.0))


def _motion_half(index: int, fs: int, count: int, band: Band) -> Strip:
    strip = _clean(index, fs, count, band)
    rng = noise_rng("motion_half", index, fs)
    return ecgnoise.noisy(strip, ecgnoise.motion_bursts(rng, strip, 0.0, coverage=0.5))


def _dropout(start_s: float) -> Builder:
    def build(index: int, fs: int, count: int, band: Band) -> Strip:
        return ecgnoise.with_dropout(_clean(index, fs, count, band), start_s, 12.0)

    return build


def _flat(index: int, fs: int, count: int, band: Band) -> Strip:
    return ecgnoise.flat_line(_clean(index, fs, count, band), level_uv=300)


def _zeros(index: int, fs: int, count: int, band: Band) -> Strip:
    return ecgnoise.flat_line(_clean(index, fs, count, band))


def _clipped(index: int, fs: int, count: int, band: Band) -> Strip:
    return ecgnoise.with_clipping(_clean(index, fs, count, band))


def _pop(index: int, fs: int, count: int, band: Band) -> Strip:
    strip = _clean(index, fs, count, band)
    at = float(noise_rng("pop", index, fs).uniform(5.0, 25.0))
    return ecgnoise.noisy(strip, ecgnoise.electrode_pop(strip, at))


BUILDERS: dict[str, Builder] = {
    "clean": lambda index, fs, count, band: _clean(index, fs, count, band),
    "white12": _white(12.0),
    "white6": _white(6.0),
    "emg6": _emg,
    "wander": _wander,
    "mains": _mains,
    "amplitude_0.3mv": _low_amplitude,
    "inverted": _inverted,
    "af": _af,
    "ectopic": _ectopic,
    "respiratory": _respiratory,
    "respiratory_slow": _respiratory_slow,
    "motion_edge": _motion_edge,
    "motion_half": _motion_half,
    "dropout_start": _dropout(0.0),
    "dropout_middle": _dropout(9.0),
    "dropout_end": _dropout(18.0),
    "flat_line": _flat,
    "all_zeros": _zeros,
    "clipping": _clipped,
    "electrode_pop": _pop,
}

# The conditions that follow the heart-rate band (the others have a rate of their own).
BANDED = (
    "clean",
    "white12",
    "white6",
    "emg6",
    "wander",
    "mains",
    "amplitude_0.3mv",
    "inverted",
    "ectopic",
    "motion_edge",
)


# Condition sets that fix a heart-rate band: name -> (condition, band). The gate rows of the
# tests file are read per band since the amendment of 2026-10-31 (#40): white noise at 12 dB and
# baseline wander pass >= 95 % from 50 bpm and may pass or fail below it; clean strips pass
# >= 95 % below 50 bpm.
SETS: dict[str, tuple[str, Band]] = {
    "clean_lt50": ("clean", LOW_BAND),
    "white12_ge50": ("white12", HIGH_BAND),
    "white12_lt50": ("white12", LOW_BAND),
    "wander_ge50": ("wander", HIGH_BAND),
    "wander_lt50": ("wander", LOW_BAND),
}


@dataclass(frozen=True)
class Case:
    condition: str  # the name asked for: a condition or a set
    sampling_hz: int
    index: int
    strip: Strip
    result: Result


@cache
def case(
    name: str, sampling_hz: int, index: int, count: int = N_SEEDS, band: Band | None = None
) -> Case:
    condition, fixed = SETS.get(name, (name, None))
    strip = BUILDERS[condition](index, sampling_hz, count, band or fixed or FULL_BAND)
    return Case(name, sampling_hz, index, strip, analyse([strip.signal_uv], sampling_hz))


def cases(
    name: str, sampling_hz: int, count: int = N_SEEDS, band: Band | None = None
) -> list[Case]:
    """``count`` seeds of a condition or set: the heart rates walk the band over the indices."""
    return [case(name, sampling_hz, i, count, band) for i in range(count)]
