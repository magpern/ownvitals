"""The seeded conditions of ADR 0006's test specification (``0006-ecg-subsystem-tests.md``).

SYNTHETIC: every strip is generated by ``ecgsynth`` and the noise models of ``ecgnoise``. A case
is ``(condition, sampling rate, seed index)``; the heart rate of a sinus condition walks the
40-180 bpm range over the seed indices, so a set of 20 seeds covers the whole range, both ends
included. Results are cached for the session: the gate, beat-matching and HR/HRV tests share
one analysis of each strip.
"""

import zlib
from collections.abc import Callable
from dataclasses import dataclass
from functools import cache

import ecgnoise
import numpy as np
from ecgsynth import Strip, make_strip

from ownvitals.ecg.pipeline import Result, analyse

SYNTHETIC = True

Builder = Callable[[int, int, int], Strip]  # (seed index, sampling rate, seed count) -> strip

RATES = (300, 500)
N_SEEDS = 20  # per condition and rate, in CI (the specification asks for at least 20)
HR_LOW, HR_HIGH = 40.0, 180.0


def sinus_hr(index: int, count: int = N_SEEDS, low: float = HR_LOW) -> float:
    """The heart rate of seed ``index``: evenly spread over ``low``-180 bpm, ends included."""
    return float(low + (HR_HIGH - low) * index / (count - 1))


def af_hr(index: int, count: int = N_SEEDS) -> float:
    """AF-like strips run at 100-150 bpm."""
    return float(100.0 + 50.0 * index / (count - 1))


def noise_rng(condition: str, index: int, fs: int) -> np.random.Generator:
    return np.random.default_rng([index, zlib.crc32(condition.encode()), fs])


def _clean(index: int, fs: int, count: int, **options: object) -> Strip:
    return make_strip(index, sinus_hr(index, count), fs, **options)  # type: ignore[arg-type]


def _white(snr_db: float) -> Builder:
    def build(index: int, fs: int, count: int) -> Strip:
        strip = _clean(index, fs, count)
        return ecgnoise.noisy(strip, ecgnoise.white(noise_rng(f"white{snr_db}", index, fs), strip, snr_db))

    return build


def _emg(index: int, fs: int, count: int) -> Strip:
    strip = _clean(index, fs, count)
    return ecgnoise.noisy(strip, ecgnoise.emg_like(noise_rng("emg6", index, fs), strip, 6.0))


def _wander(index: int, fs: int, count: int) -> Strip:
    strip = _clean(index, fs, count)
    return ecgnoise.noisy(strip, ecgnoise.baseline_wander(noise_rng("wander", index, fs), strip))


def _mains(index: int, fs: int, count: int) -> Strip:
    strip = _clean(index, fs, count)
    nominal = 50.0 if index % 2 == 0 else 60.0
    return ecgnoise.noisy(strip, ecgnoise.mains(noise_rng("mains", index, fs), strip, nominal))


def _low_amplitude(index: int, fs: int, count: int) -> Strip:
    return _clean(index, fs, count, amplitude_mv=0.3)


def _inverted(index: int, fs: int, count: int) -> Strip:
    return _clean(index, fs, count, polarity=-1)


def _af(index: int, fs: int, count: int) -> Strip:
    return make_strip(index, af_hr(index, count), fs, kind="af")


def _ectopic(index: int, fs: int, count: int) -> Strip:
    return _clean(index, fs, count, kind="ectopic", n_ectopic=1 + index % 2)


def _respiratory(index: int, fs: int, count: int) -> Strip:
    """Respiratory modulation of +-12 % at 0.25 Hz, 55-180 bpm (where only the first interval
    can be excluded)."""
    return make_strip(index, sinus_hr(index, count, low=55.0), fs, kind="respiratory")


def _respiratory_slow(index: int, fs: int, count: int) -> Strip:
    """The same at 40 and 45 bpm (alternating), where section 8's 20 % rule drops real
    intervals."""
    return make_strip(index, 40.0 if index % 2 == 0 else 45.0, fs, kind="respiratory")


def _motion_edge(index: int, fs: int, count: int) -> Strip:
    """One burst of 1-3 s at 0 dB at the start (even index) or the end (odd index)."""
    strip = _clean(index, fs, count)
    rng = noise_rng("motion_edge", index, fs)
    length = float(rng.uniform(1.0, 3.0))
    start = 0.0 if index % 2 == 0 else 30.0 - length
    return ecgnoise.noisy(strip, ecgnoise.motion_burst(rng, strip, start, length, 0.0))


def _motion_half(index: int, fs: int, count: int) -> Strip:
    strip = _clean(index, fs, count)
    rng = noise_rng("motion_half", index, fs)
    return ecgnoise.noisy(strip, ecgnoise.motion_bursts(rng, strip, 0.0, coverage=0.5))


def _dropout(start_s: float) -> Builder:
    def build(index: int, fs: int, count: int) -> Strip:
        return ecgnoise.with_dropout(_clean(index, fs, count), start_s, 12.0)

    return build


def _flat(index: int, fs: int, count: int) -> Strip:
    return ecgnoise.flat_line(_clean(index, fs, count), level_uv=300)


def _zeros(index: int, fs: int, count: int) -> Strip:
    return ecgnoise.flat_line(_clean(index, fs, count))


def _clipped(index: int, fs: int, count: int) -> Strip:
    return ecgnoise.with_clipping(_clean(index, fs, count))


def _pop(index: int, fs: int, count: int) -> Strip:
    strip = _clean(index, fs, count)
    at = float(noise_rng("pop", index, fs).uniform(5.0, 25.0))
    return ecgnoise.noisy(strip, ecgnoise.electrode_pop(strip, at))


BUILDERS: dict[str, Builder] = {
    "clean": lambda index, fs, count: _clean(index, fs, count),
    "white12": _white(12.0),
    "white6": _white(6.0),
    "emg6": _emg,
    "wander": _wander,
    "mains": _mains,
    "amplitude_0.3mv": _low_amplitude,
    "inverted": _inverted,
    "af": _af,
    "ectopic": _ectopic,
    "respiratory": _respiratory,
    "respiratory_slow": _respiratory_slow,
    "motion_edge": _motion_edge,
    "motion_half": _motion_half,
    "dropout_start": _dropout(0.0),
    "dropout_middle": _dropout(9.0),
    "dropout_end": _dropout(18.0),
    "flat_line": _flat,
    "all_zeros": _zeros,
    "clipping": _clipped,
    "electrode_pop": _pop,
}


@dataclass(frozen=True)
class Case:
    condition: str
    sampling_hz: int
    index: int
    strip: Strip
    result: Result


@cache
def case(condition: str, sampling_hz: int, index: int, count: int = N_SEEDS) -> Case:
    strip = BUILDERS[condition](index, sampling_hz, count)
    return Case(condition, sampling_hz, index, strip, analyse([strip.signal_uv], sampling_hz))


def cases(condition: str, sampling_hz: int, count: int = N_SEEDS) -> list[Case]:
    """``count`` seeds of a condition: the heart rates walk 40-180 bpm over the indices."""
    return [case(condition, sampling_hz, i, count) for i in range(count)]
