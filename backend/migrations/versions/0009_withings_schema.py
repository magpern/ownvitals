def _series(name: str, kind: str) -> str:
    """``sleep_series`` (``series``) or ``intraday`` (``metric``). Monthly on ``ts``."""
    return f"""
CREATE TABLE public.{name} (
    id uuid NOT NULL DEFAULT gen_random_uuid(),
    owner_id uuid NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
    ts timestamptz NOT NULL,
    source_tz text NOT NULL CONSTRAINT {name}_source_tz CHECK ({_TZ}),
    connection_id uuid NOT NULL,
    {kind} text NOT NULL CONSTRAINT {name}_{kind} CHECK ({kind} ~ '^[a-z][a-z0-9_]{{0,39}}$'),
    value_raw bigint NOT NULL,
    unit integer NOT NULL,
    PRIMARY KEY (owner_id, id, ts),
    UNIQUE (owner_id, connection_id, {kind}, ts),
    FOREIGN KEY (owner_id, connection_id) REFERENCES public.connections (owner_id, id)
        ON DELETE CASCADE
) PARTITION BY RANGE (ts)"""


