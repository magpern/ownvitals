"""raw Withings data model (PLAN section 5, ADR 0002, roadmap Amendment 2; #21)

Revision ID: 0009_withings_schema
Revises: 0008_withings_jobs
Create Date: 2026-11-02

Owned tables get ``owner_id``, ``UNIQUE (owner_id, id)`` (partitioned tables use
``PRIMARY KEY (owner_id, id, ts)`` instead), owner-inclusive foreign keys and forced RLS.
``withings_apps`` and ``webhook_events`` are system tables. The app role may only read the
listed ``withings_apps`` columns and has no privilege on ``webhook_events``.

Partitions are not created here. ``ensure_month_partitions`` (docker/postgres/withings/)
creates a month when a writer asks for it. Webhook-secret and webhook-event functions are
not created here either (ADR 0005 section 3).

``connections`` gains generated ``app_id``, ``withings_userid`` and ``scopes`` from ``public``,
and the one owner-less unique index ADR 0002 section 2 allows. This migration moves no data
and bypasses no row-level security.
"""

